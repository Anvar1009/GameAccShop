export const translations: Record<Language, Record<TranslationKey, string>> = {
  uz,
  ru,
  en,
};

export type TranslateParams = Record<string, string | number>;

export function interpolate(template: string, params?: TranslateParams): string {
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (match, key: string) =>
    key in params ? String(params[key]) : match
  );
}

export function readStoredLanguage(): Language {
  if (typeof window === "undefined") return DEFAULT_LANGUAGE;
  const stored = window.localStorage.getItem(STORAGE_KEY);
  if (stored && stored in translations) return stored as Language;
  return DEFAULT_LANGUAGE;
}

/**
 * Standalone translator for use OUTSIDE React components (e.g. react-query
 * hooks and toasts). Reads the current language from localStorage at call
 * time, so toasts always render in the active language.
 */
export function translate(
  key: TranslationKey,
  params?: TranslateParams,
  lang: Language = readStoredLanguage()
): string {
  const template = translations[lang][key] ?? translations.en[key] ?? key;
  return interpolate(template, params);
}
